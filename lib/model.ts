// Token Radar — the value model (radar-2).
//
// One function scores every protocol from the sealed snapshot alone. No protocol
// name is ever special-cased: the same arithmetic ranks a $2.7B risk curator and a
// $6M DEX, and the dashboard recomputes every row from the same figures.
//
//   implied = round( tvl_usd
//                    x category_multiple(category)
//                    x growth_multiplier(change_7d)
//                    x maturity_multiplier(age_days)
//                    x breadth_multiplier(chains) )
//
// Why each factor is there:
// - category_multiple: a token's market cap is a multiple of the TVL it secures,
//   and that multiple differs by business. Exchange and perps tokens trade at the
//   highest multiples of TVL; lending and collateral next; vault curators a little
//   lower; RWA lower still (regulated, slower token upside); bridges and staking
//   products lowest (their value is mostly the asset they wrap, not a new token).
// - growth_multiplier: seven-day TVL change, clamped to [-40, +60] so one freak
//   week cannot crown a protocol. Falls are punished twice as hard as rises are
//   rewarded (weight 1.2 down, 0.6 up): a protocol bleeding TVL is a worse launch
//   candidate than a flat one, and a hot week is weaker evidence than a cold one.
// - maturity_multiplier: a smooth square-root curve over age, 0.55 at listing to
//   1.00 at four years. A protocol that has run for years with no token has earned
//   its launch; a two-week-old one has not, however large its TVL.
// - breadth_multiplier: +2% per extra chain, capped at +10%. TVL spread across
//   chains is stickier than TVL on one chain, and a launch reaches more farmers.
//
// The board ranks 200 rows: all 40 watchlist protocols plus the 160 largest
// pre-token protocols below the $50M floor, by TVL. Live-token protocols are
// never ranked — they are set aside with their market caps shown, so the board
// never confuses a traded price with a modelled one.

